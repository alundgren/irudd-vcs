func TestCreateDelegateHooksPermissions(t *testing.T) {
	hookDir := t.TempDir()
	existingHookDir := filepath.Join(hookDir, "post-receive.d")
	require.NoError(t, os.MkdirAll(existingHookDir, 0o777))
	require.NoError(t, os.Chmod(existingHookDir, 0o777))

	require.NoError(t, createDelegateHooks(hookDir))

	hookNames, _, _ := getHookTemplates()
	for _, hookName := range hookNames {
		for _, path := range []string{
			filepath.Join(hookDir, hookName),
			filepath.Join(hookDir, hookName+".d"),
			filepath.Join(hookDir, hookName+".d", "gitea"),
		} {
			info, err := os.Stat(path)
			require.NoError(t, err)
			require.Equal(t, os.FileMode(0o755), info.Mode().Perm(), path)
		}
	}
}

// hookShell finds the shell that git runs hooks with, avoiding the WSL bash on Windows
func hookShell(t *testing.T) string {
	if runtime.GOOS != "windows" {
		sh, err := exec.LookPath("sh")
		if err != nil {
			t.Skip("no sh")
		}
		return sh
	}
	out, err := exec.Command("git", "--exec-path").Output()
	if err != nil {
		t.Skip("no git")
	}
	// <git>/mingw64/libexec/git-core
	sh := filepath.Join(strings.TrimSpace(string(out)), "..", "..", "..", "bin", "sh.exe")
	if _, err := os.Stat(sh); err != nil {
		t.Skip("no sh next to git")
	}
	return sh
}

func TestHookDispatcher(t *testing.T) {
	sh := hookShell(t)
	const refs = "old new refs/heads/main\n"

	run := func(t *testing.T, hookName string, hooks map[string]string) (string, int) {
		gitDir := t.TempDir()
		hookDir := filepath.Join(gitDir, "hooks")
		require.NoError(t, os.MkdirAll(filepath.Join(hookDir, hookName+".d"), 0o755))
		require.NoError(t, os.WriteFile(filepath.Join(hookDir, hookName), []byte(hookDispatcherTpl()), 0o755))
		for name, body := range hooks {
			require.NoError(t, os.WriteFile(filepath.Join(hookDir, hookName+".d", name), []byte("#!/bin/sh\n"+body+"\n"), 0o755))
		}
		cmd := exec.Command(sh, filepath.ToSlash(filepath.Join(hookDir, hookName)))
		cmd.Env = append(os.Environ(), "GIT_DIR="+filepath.ToSlash(gitDir))
		cmd.Stdin = strings.NewReader(refs)
		out, err := cmd.Output()
		code := 0
		if exitErr, ok := errors.AsType[*exec.ExitError](err); ok {
			code = exitErr.ExitCode()
		} else {
			require.NoError(t, err)
		}
		return strings.ReplaceAll(string(out), "\r", ""), code
	}

	t.Run("SourcesGitea", func(t *testing.T) {
		out, code := run(t, "pre-receive", map[string]string{"gitea": `echo "gitea $hookname"; exec cat`})
		assert.Equal(t, "gitea pre-receive\n"+refs, out) // $hookname is only set when sourced
		assert.Zero(t, code)
	})
	t.Run("GiteaWithoutExec", func(t *testing.T) {
		out, code := run(t, "post-receive", map[string]string{"gitea": "cat; false"})
		assert.Equal(t, refs, out) // runs once and keeps its status
		assert.Equal(t, 1, code)
	})
	t.Run("SingleCustom", func(t *testing.T) {
		out, code := run(t, "pre-receive", map[string]string{"pre-receive": `echo "custom $hookname"; cat; exit 2`})
		assert.Equal(t, "custom \n"+refs, out) // exec'd, not sourced
		assert.Equal(t, 2, code)
	})
	t.Run("Several", func(t *testing.T) {
		out, code := run(t, "pre-receive", map[string]string{"gitea": "echo gitea; cat", "pre-receive": "echo custom; cat; exit 4"})
		assert.Equal(t, "gitea\n"+refs+"custom\n"+refs, out)
		assert.Equal(t, 4, code)
	})
	t.Run("None", func(t *testing.T) {
		out, code := run(t, "pre-receive", nil)
		assert.Empty(t, out)
		assert.Zero(t, code)
	})
}

func TestRemoveGiteaUpdateHook(t *testing.T) {
	writeUpdateHooks := func(t *testing.T, hooks ...string) string {
		hookDir := t.TempDir()
		require.NoError(t, os.MkdirAll(filepath.Join(hookDir, "update.d"), 0o755))
		require.NoError(t, os.WriteFile(filepath.Join(hookDir, "update"), []byte("#!/bin/sh\n# AUTO GENERATED BY GITEA, DO NOT MODIFY\n"), 0o755))
		for _, name := range hooks {
			require.NoError(t, os.WriteFile(filepath.Join(hookDir, "update.d", name), []byte("#!/bin/sh\n"), 0o755))
		}
		return hookDir
	}

	hookDir := writeUpdateHooks(t, "gitea")
	require.NoError(t, createDelegateHooks(hookDir))
	assert.NoFileExists(t, filepath.Join(hookDir, "update"))
	assert.NoDirExists(t, filepath.Join(hookDir, "update.d"))
	assert.FileExists(t, filepath.Join(hookDir, "pre-receive.d", "gitea"))

	// another update hook keeps its dispatcher
	hookDir = writeUpdateHooks(t, "gitea", "custom")
	require.NoError(t, createDelegateHooks(hookDir))
	assert.FileExists(t, filepath.Join(hookDir, "update"))
	assert.FileExists(t, filepath.Join(hookDir, "update.d", "custom"))
	assert.NoFileExists(t, filepath.Join(hookDir, "update.d", "gitea"))

	// the oldest dispatchers carry no marker
	hookDir = writeUpdateHooks(t, "gitea")
	require.NoError(t, os.WriteFile(filepath.Join(hookDir, "update"), []byte("#!/usr/bin/env bash\nfor i in `ls \"$SHELL_FOLDER/update.d\"`; do\n    sh \"$SHELL_FOLDER/update.d/$i\" $1 $2 $3\ndone"), 0o755))
	require.NoError(t, createDelegateHooks(hookDir))
	assert.NoFileExists(t, filepath.Join(hookDir, "update"))

	// an update hook that Gitea did not write stays
	hookDir = t.TempDir()
	require.NoError(t, os.WriteFile(filepath.Join(hookDir, "update"), []byte("#!/bin/sh\nexit 0\n"), 0o755))
	require.NoError(t, createDelegateHooks(hookDir))
	assert.FileExists(t, filepath.Join(hookDir, "update"))
}

func TestGiteaPreReceiveHook(t *testing.T) {
	sh := hookShell(t)
	dir := t.TempDir()
	fakeGitea := filepath.Join(dir, "fake-gitea")
	require.NoError(t, os.WriteFile(fakeGitea, []byte("#!/bin/sh\necho \"gitea $*\"\ncat\n"), 0o755))
	defer test.MockVariableValue(&setting.AppPath, filepath.ToSlash(fakeGitea))()
	defer test.MockVariableValue(&setting.CustomConf, "app.ini")()
	_, _, giteaHookTpls := getHookTemplates()
	hook := filepath.Join(dir, "gitea")
	require.NoError(t, os.WriteFile(hook, []byte(giteaHookTpls[0]), 0o755))

	run := func(noRefRules, refs string) string {
		cmd := exec.Command(sh, filepath.ToSlash(hook))
		cmd.Env = append(os.Environ(), "GITEA_NO_REF_RULES="+noRefRules)
		cmd.Stdin = strings.NewReader(refs)
		out, err := cmd.Output()
		require.NoError(t, err)
		return strings.ReplaceAll(string(out), "\r", "")
	}
	const zero = "0000000000000000000000000000000000000000"
	const gitea = "gitea hook --config=app.ini pre-receive\n"
	update := "a1 b1 refs/heads/main\na2 b2 refs/tags/v1\n"
	deleteMain := "a1 " + zero + " refs/heads/main\n"

	assert.Equal(t, gitea+update, run("", update), "rules apply: gitea checks every ref")
	assert.Empty(t, run("main", update), "no rules: nothing to check")
	assert.Empty(t, run("main", "a1 "+zero+" refs/heads/other\n"), "deleting another branch is allowed")
	assert.Equal(t, gitea+update+deleteMain, run("main", update+deleteMain), "deleting the default branch is gitea's to refuse")
	assert.Empty(t, run("main", ""))
}

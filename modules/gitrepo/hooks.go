// hookDispatcherTpl runs every executable in hooks/<name>.d. With a single hook, which is the
// usual case, it execs that hook directly: each fork costs 10-20 ms on Windows, and a push runs
// two hooks. Gitea's own hook is sourced, which saves starting a shell. Hooks take their input from stdin.
func hookDispatcherTpl() string {
	return fmt.Sprintf(`#!/usr/bin/env %s
# AUTO GENERATED BY GITEA, DO NOT MODIFY
hookname=${0##*/}
GIT_DIR=${GIT_DIR:-${0%%/*}/..}
count=0
for hook in "${GIT_DIR}/hooks/${hookname}.d"/*; do
  test -x "${hook}" && test -f "${hook}" || continue
  count=$((count + 1))
  last=${hook}
done
if [ ${count} -eq 1 ]; then
  case ${last} in */gitea) . "${last}"; exit $? ;; esac
  exec "${last}"
fi
data=$(cat)
exitcodes=""
for hook in "${GIT_DIR}/hooks/${hookname}.d"/*; do
  test -x "${hook}" && test -f "${hook}" || continue
  echo "${data}" | "${hook}"
  exitcodes="${exitcodes} $?"
done

for i in ${exitcodes}; do
  [ ${i} -eq 0 ] || exit ${i}
done
`, setting.ScriptType)
}

func getHookTemplates() (hookNames, hookTpls, giteaHookTpls []string) {
	hookNames = []string{"pre-receive", "post-receive"}
	hookTpls = []string{hookDispatcherTpl(), hookDispatcherTpl()}

	// exec, since the dispatcher sources these and a shell waiting on gitea is one more process
	giteaHookTpls = []string{
		// for pre-receive
		fmt.Sprintf(`#!/usr/bin/env %s
# AUTO GENERATED BY GITEA, DO NOT MODIFY
exec %s hook --config=%s pre-receive
`, setting.ScriptType, util.ShellEscape(setting.AppPath), util.ShellEscape(setting.CustomConf)),

		// for post-receive
		fmt.Sprintf(`#!/usr/bin/env %s
# AUTO GENERATED BY GITEA, DO NOT MODIFY
exec %s hook --config=%s post-receive
`, setting.ScriptType, util.ShellEscape(setting.AppPath), util.ShellEscape(setting.CustomConf)),
	}

	return hookNames, hookTpls, giteaHookTpls
}

// HookTemplatesHash identifies the generated hooks, which change with the templates and settings
func HookTemplatesHash() string {
	_, hookTpls, giteaHookTpls := getHookTemplates()
	h := sha256.New()
	for _, tpl := range append(hookTpls, giteaHookTpls...) {
		_, _ = io.WriteString(h, tpl)
		_, _ = h.Write([]byte{0})
	}
	return hex.EncodeToString(h.Sum(nil))
}

// CreateDelegateHooks creates all the hooks scripts for the repo
func CreateDelegateHooks(_ context.Context, repo Repository) (err error) {
	return createDelegateHooks(filepath.Join(repoPath(repo), "hooks"))
}

func createDelegateHooks(hookDir string) (err error) {
	hookNames, hookTpls, giteaHookTpls := getHookTemplates()

	for i, hookName := range hookNames {
		oldHookPath := filepath.Join(hookDir, hookName)
		newHookPath := filepath.Join(hookDir, hookName+".d", "gitea")

		hookDDir := filepath.Join(hookDir, hookName+".d")
		if err := os.MkdirAll(hookDDir, 0o755); err != nil {
			return fmt.Errorf("create hooks dir '%s': %w", hookDDir, err)
		}
		if err := os.Chmod(hookDDir, 0o755); err != nil {
			return fmt.Errorf("chmod hooks dir '%s': %w", hookDDir, err)
		}

		// WARNING: This will override all old server-side hooks
		if err = util.Remove(oldHookPath); err != nil && !os.IsNotExist(err) {
			return fmt.Errorf("unable to pre-remove old hook file '%s' prior to rewriting: %w ", oldHookPath, err)
		}
		if err = os.WriteFile(oldHookPath, []byte(hookTpls[i]), 0o755); err != nil {
			return fmt.Errorf("write old hook file '%s': %w", oldHookPath, err)
		}

		if err = ensureExecutable(oldHookPath); err != nil {
			return fmt.Errorf("Unable to set %s executable. Error %w", oldHookPath, err)
		}

		if err = util.Remove(newHookPath); err != nil && !os.IsNotExist(err) {
			return fmt.Errorf("unable to pre-remove new hook file '%s' prior to rewriting: %w", newHookPath, err)
		}
		if err = os.WriteFile(newHookPath, []byte(giteaHookTpls[i]), 0o755); err != nil {
			return fmt.Errorf("write new hook file '%s': %w", newHookPath, err)
		}

		if err = ensureExecutable(newHookPath); err != nil {
			return fmt.Errorf("Unable to set %s executable. Error %w", oldHookPath, err)
		}
	}

	return removeGiteaUpdateHook(hookDir)
}

// removeGiteaUpdateHook removes the update hook that Gitea used to install: receive.hideRefs now rejects
// client writes to refs/pull, and git ran the hook for every pushed ref. The dispatcher stays while
// other hooks in update.d need it.
func removeGiteaUpdateHook(hookDir string) error {
	hookDDir := filepath.Join(hookDir, "update.d")
	if err := util.Remove(filepath.Join(hookDDir, "gitea")); err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("remove old update hook: %w", err)
	}
	entries, err := os.ReadDir(hookDDir)
	if err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("read update hooks dir: %w", err)
	}
	if len(entries) > 0 {
		return nil
	}
	if err := util.Remove(hookDDir); err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("remove update hooks dir: %w", err)
	}
	dispatcher := filepath.Join(hookDir, "update")
	// a dispatcher only runs update.d, which the oldest Gitea ones did without the generated marker
	if content, err := os.ReadFile(dispatcher); err == nil && (strings.Contains(string(content), "AUTO GENERATED BY GITEA") || strings.Contains(string(content), "update.d")) {
		if err := util.Remove(dispatcher); err != nil {
			return fmt.Errorf("remove update hook dispatcher: %w", err)
		}
	}
	return nil
}

func checkExecutable(filename string) bool {
	// windows has no concept of a executable bit
	if runtime.GOOS == "windows" {
		return true
	}
	fileInfo, err := os.Stat(filename)
	if err != nil {
		return false
	}
	return (fileInfo.Mode() & 0o100) > 0
}

func ensureExecutable(filename string) error {
	fileInfo, err := os.Stat(filename)
	if err != nil {
		return err
	}
	if (fileInfo.Mode() & 0o100) > 0 {
		return nil
	}
	mode := fileInfo.Mode() | 0o100
	return os.Chmod(filename, mode)
}

// CheckDelegateHooks checks the hooks scripts for the repo
func CheckDelegateHooks(_ context.Context, repo Repository) ([]string, error) {
	return checkDelegateHooks(filepath.Join(repoPath(repo), "hooks"))
}

func checkDelegateHooks(hookDir string) ([]string, error) {
	hookNames, hookTpls, giteaHookTpls := getHookTemplates()

	results := make([]string, 0, 10)

	for i, hookName := range hookNames {
		oldHookPath := filepath.Join(hookDir, hookName)
		newHookPath := filepath.Join(hookDir, hookName+".d", "gitea")

		cont := false
		isExist, err := util.IsExist(oldHookPath)
		if err != nil {
			results = append(results, fmt.Sprintf("unable to check if %s exists. Error: %v", oldHookPath, err))
		}
		if err == nil && !isExist {
			results = append(results, fmt.Sprintf("old hook file %s does not exist", oldHookPath))
			cont = true
		}
		isExist, err = util.IsExist(oldHookPath + ".d")
		if err != nil {
			results = append(results, fmt.Sprintf("unable to check if %s exists. Error: %v", oldHookPath+".d", err))
		}
		if err == nil && !isExist {
			results = append(results, fmt.Sprintf("hooks directory %s does not exist", oldHookPath+".d"))
			cont = true
		}
		isExist, err = util.IsExist(newHookPath)
		if err != nil {
			results = append(results, fmt.Sprintf("unable to check if %s exists. Error: %v", newHookPath, err))
		}
		if err == nil && !isExist {
			results = append(results, fmt.Sprintf("new hook file %s does not exist", newHookPath))
			cont = true
		}
		if cont {
			continue
		}
		contents, err := os.ReadFile(oldHookPath)
		if err != nil {
			return results, err
		}
		if string(contents) != hookTpls[i] {
			results = append(results, fmt.Sprintf("old hook file %s is out of date", oldHookPath))
		}
		if !checkExecutable(oldHookPath) {
			results = append(results, fmt.Sprintf("old hook file %s is not executable", oldHookPath))
		}
		contents, err = os.ReadFile(newHookPath)
		if err != nil {
			return results, err
		}
		if string(contents) != giteaHookTpls[i] {
			results = append(results, fmt.Sprintf("new hook file %s is out of date", newHookPath))
		}
		if !checkExecutable(newHookPath) {
			results = append(results, fmt.Sprintf("new hook file %s is not executable", newHookPath))
		}
	}
	return results, nil
}
